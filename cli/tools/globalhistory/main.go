// Command globalhistory writes the sha256 of every version of each global template
// (templates/global/...) the repository's history holds, so setup and update can tell a file
// holding an earlier makeit release's text from one the user wrote.
package main

import (
	"bytes"
	"crypto/sha256"
	"encoding/hex"
	"flag"
	"fmt"
	"os"
	"os/exec"
	"slices"
	"strings"
)

func git(repo string, args ...string) ([]byte, error) {
	cmd := exec.Command("git", append([]string{"-c", "safe.directory=*", "-C", repo}, args...)...)
	cmd.Stderr = os.Stderr
	return cmd.Output()
}

func main() {
	repo := flag.String("repo", "..", "repository root")
	out := flag.String("out", "", "file to write (stdout when empty)")
	flag.Parse()
	// A shallow clone (CI, the release build) or no git holds too little history: the committed
	// file stays, or the release would forget every earlier version.
	if sh, err := git(*repo, "rev-parse", "--is-shallow-repository"); err != nil || strings.TrimSpace(string(sh)) != "false" {
		fmt.Fprintln(os.Stderr, "globalhistory: no full git history here; keeping the committed file")
		return
	}
	commits, err := git(*repo, "log", "--format=%H", "--", "templates/global")
	if err != nil {
		fmt.Fprintln(os.Stderr, "globalhistory:", err)
		os.Exit(1)
	}
	seen := map[string]map[string]bool{}
	for _, c := range strings.Fields(string(commits)) {
		names, err := git(*repo, "ls-tree", "-r", "--name-only", c, "--", "templates/global")
		if err != nil {
			fmt.Fprintln(os.Stderr, "globalhistory:", err)
			os.Exit(1)
		}
		for _, p := range strings.Fields(string(names)) {
			data, err := git(*repo, "show", c+":"+p)
			if err != nil {
				fmt.Fprintln(os.Stderr, "globalhistory:", err)
				os.Exit(1)
			}
			h := sha256.Sum256(data)
			if seen[p] == nil {
				seen[p] = map[string]bool{}
			}
			seen[p]["sha256:"+hex.EncodeToString(h[:])] = true
		}
	}
	var b bytes.Buffer
	b.WriteString("// Code generated by tools/globalhistory; DO NOT EDIT.\n\npackage setup\n\n")
	b.WriteString("// globalHistory holds the sha256 of every version of each global template makeit's history\n")
	b.WriteString("// holds: a file still holding one of them was written by makeit, not by the user.\n")
	b.WriteString("var globalHistory = map[string][]string{\n")
	paths := make([]string, 0, len(seen))
	for p := range seen {
		paths = append(paths, p)
	}
	slices.Sort(paths)
	for _, p := range paths {
		hashes := make([]string, 0, len(seen[p]))
		for h := range seen[p] {
			hashes = append(hashes, h)
		}
		slices.Sort(hashes)
		fmt.Fprintf(&b, "\t%q: {\n", p)
		for _, h := range hashes {
			fmt.Fprintf(&b, "\t\t%q,\n", h)
		}
		b.WriteString("\t},\n")
	}
	b.WriteString("}\n")
	if *out == "" {
		os.Stdout.Write(b.Bytes())
		return
	}
	if err := os.WriteFile(*out, b.Bytes(), 0o644); err != nil {
		fmt.Fprintln(os.Stderr, "globalhistory:", err)
		os.Exit(1)
	}
}
